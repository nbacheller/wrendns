"""Tests for scripts/check-spdx.py (ADR-1033, ADR-1035). Run: python3 scripts/test_check_spdx.py"""

from __future__ import annotations

import importlib.util
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC = importlib.util.spec_from_file_location("check_spdx", HERE / "check-spdx.py")
assert SPEC and SPEC.loader
spdx = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(spdx)

HDR_RS = "// SPDX-License-Identifier: AGPL-3.0-or-later\n"


class Scope(unittest.TestCase):
    def test_lic_001_extensions_in_scope(self):
        for path in ["crates/a/src/x.rs", "ui/src/A.svelte", "ui/x.ts", "a.js", "s.sh", "t.py"]:
            self.assertTrue(spdx.in_scope(path), path)
        for path in ["README.md", "x.toml", "ui/x.css", "x.html", "x.json"]:
            self.assertFalse(spdx.in_scope(path), path)

    def test_lic_001_exclusions(self):
        for path in [
            "integrations/home-assistant/custom_components/wrendns/x.py",
            "ui/node_modules/p/index.js",
            "crates/wrendns/testdata/a/make.py",
            "ui/tests/e2e/fixtures/x.ts",
            "crates/x/vendor/y.rs",
            ".github/issues-archive/x.py",
        ]:
            self.assertFalse(spdx.in_scope(path), path)

    def test_lic_001_generated_is_exempt(self):
        self.assertTrue(spdx.is_generated("/**\n * This file was auto-generated by openapi-typescript.\n"))
        self.assertTrue(spdx.is_generated("// GENERATED by ui/scripts/brand-icons.mjs\n"))
        self.assertTrue(spdx.is_generated("// REQ: X - generated by `gen.py`; do not edit.\n"))
        self.assertFalse(spdx.is_generated("// A file that mentions generated output later.\nfn main() {}\n"))
        self.assertFalse(spdx.is_generated("// Parses the auto-generated report the router writes.\n"))
        self.assertFalse(spdx.is_generated("x = 1  # @generated\n"))
        self.assertTrue(spdx.is_generated("# @generated by build.rs\n"))

    def test_lic_001_header_position(self):
        self.assertTrue(spdx.has_header(HDR_RS + "fn main() {}\n"))
        self.assertTrue(spdx.has_header("#!/bin/sh\n# SPDX-License-Identifier: AGPL-3.0-or-later\n"))
        self.assertTrue(spdx.has_header("<!-- SPDX-License-Identifier: AGPL-3.0-or-later -->\n<script>\n"))
        self.assertFalse(spdx.has_header("// SPDX-License-Identifier: MIT\n"))
        self.assertFalse(spdx.has_header("\n" * 6 + HDR_RS))


class Repo(unittest.TestCase):
    """End to end in a throwaway git repository: only files added after the tag are checked."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        env = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@example.invalid",
               "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@example.invalid"}
        self.env = env
        self.git("init", "-q")
        self.write("old.rs", "fn old() {}\n")
        self.write("moved.py", "print(1)\n")
        self.git("add", ".")
        self.git("commit", "-qm", "base")
        self.git("tag", "-a", "permissive-final", "-m", "baseline")

    def tearDown(self):
        self.tmp.cleanup()

    def git(self, *args):
        subprocess.run(["git", *args], cwd=self.root, check=True, env=self.env, capture_output=True)

    def write(self, rel, text):
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")

    def run_check(self):
        return subprocess.run([sys.executable, str(HERE / "check-spdx.py")], cwd=self.root,
                              capture_output=True, text=True, env=self.env)

    def test_lic_001_old_and_renamed_files_are_not_checked(self):
        self.write("old.rs", "fn old() { /* edited */ }\n")
        self.git("mv", "moved.py", "renamed.py")
        self.git("commit", "-qam", "edit and rename")
        res = self.run_check()
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)

    def test_lic_001_a_half_copied_file_is_new(self):
        lines = [f"line_{i} = {i}\n" for i in range(10)]
        self.write("big.py", "".join(lines))
        self.git("add", ".")
        self.git("commit", "-qm", "big")
        self.git("tag", "-f", "-a", "permissive-final", "-m", "baseline")
        self.git("rm", "-q", "big.py")
        self.write("borrowed.py", "".join(lines[:6]) + "".join(f"new_{i} = {i}\n" for i in range(4)))
        self.git("add", ".")
        self.git("commit", "-qm", "borrow")
        res = self.run_check()
        self.assertEqual(res.returncode, 1, res.stdout + res.stderr)
        self.assertIn("borrowed.py", res.stdout)

    def test_lic_001_new_file_without_header_fails(self):
        self.write("new.rs", "fn new() {}\n")
        self.write("ok.rs", HDR_RS + "fn ok() {}\n")
        self.git("add", ".")
        self.git("commit", "-qm", "new files")
        self.write("untracked.ts", "export {};\n")
        res = self.run_check()
        self.assertEqual(res.returncode, 1)
        self.assertIn("new.rs", res.stdout)
        self.assertIn("untracked.ts", res.stdout)
        self.assertNotIn("ok.rs", res.stdout)

    def test_lic_001_missing_tag_is_a_clear_error(self):
        self.git("tag", "-d", "permissive-final")
        res = self.run_check()
        self.assertNotEqual(res.returncode, 0)
        self.assertIn("fetch-depth: 0", res.stderr)


if __name__ == "__main__":
    unittest.main(verbosity=2)
