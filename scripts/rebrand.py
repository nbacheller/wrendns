#!/usr/bin/env python3
"""Rename TelltaleDNS to WrenDNS across the repository (spec/10 T33.2, ADR-1026, ADR-1029).

Deterministic and idempotent: a second run changes nothing. `--check` changes nothing and exits
non-zero when anything is left to rename (CI can run it). `--list` prints what would change.

Replay (the rename must be redoable when the base moves on):

    git merge <latest base>                       # or start a new branch from it
    python3 scripts/rebrand.py                    # rewrite text, rename files and directories
    cargo fmt --all                               # "wrendns" is one letter shorter than "telltale"
    git add -A && git commit -m "chore: rename TelltaleDNS to WrenDNS (generated by scripts/rebrand.py) [T33.2]"

then re-apply the hand-written commits that follow it (the compatibility shims, ADR-1028). The
script never touches the git index: it enumerates tracked and untracked-but-not-ignored files,
rewrites them in place and moves renamed ones on disk.

What it rewrites
----------------
Every text file (UTF-8, no NUL) and every file or directory name, by the ordered table RULES
below. The order matters: longer and more specific spellings first. Cargo.lock is rewritten the
same way and then re-sorted, because the package list is ordered by name.

What it keeps (the KEEP list; ADR-1029 states the history rule)
---------------------------------------------------------------
* KEEP_PATHS: the licence texts, `brand/`, `.github/issues-archive/`, `spec/upstream.md`, the notes
  of published releases (`deploy/release/notes/v0.1.0.md` to `v0.7.x`), the
  deploy secrets directory (never read), this script, and the compatibility shims (files whose
  whole point is to name the old spelling).
* KEEP_TOKENS: attributions that point at upstream (`paimonsoror/telltaledns`: the repository,
  its issues and commits; install, download, image and site URLs are the project's own and move
  to the fork's owner and to wrendns.com, see RULES),
  the upstream copyright line (`The TelltaleDNS Authors`) and `nbacheller/telltaledns`, the GitHub
  repository's slug, which stays until the owner renames the repository.
* KEEP_SECTIONS: text that records the rename or the old name as history. The rule: *current-tense
  prose and every identifier is renamed; a statement of what the project was called, and the
  records of the rename itself, are history and stay.* Concretely: ADR-1026, ADR-1028 to
  ADR-1030 and ADR-1033 (the licence, which names upstream's product) in spec/11, the T33.x task entries in spec/10, and the version-numbered (past-release)
  sections of any CHANGELOG*.md.
* KEEP_LINE_REGEX: format identifiers that are stored in files users already have (the backup
  manifest's `telltale_version` field).
* Inline markers, for anything else that must keep an old spelling: a line containing
  `rebrand:keep` is left alone; lines between `rebrand:keep-start` and `rebrand:keep-end` are left
  alone. They are used for on-disk and on-the-wire formats (cryptographic labels, the backup
  format name, certificate names used during a rolling upgrade) and in the compatibility code.
"""

from __future__ import annotations

import argparse
import fnmatch
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# ---------------------------------------------------------------------------------------------
# The mapping. Applied top to bottom to every text line and every path. "protect" freezes the
# KEEP_TOKENS (replaced by sentinels, restored at the end) so the later, general rules skip them.
# ---------------------------------------------------------------------------------------------
KEEP_TOKENS = [
    "paimonsoror/telltaledns",  # upstream: repository, issues, releases, badges
    "The TelltaleDNS Authors",  # the upstream copyright line
    "nbacheller/telltaledns",  # this repository's slug, until it is renamed (ADR-1026)
]

RULES = [
    # The project's own artifacts live under the fork's owner (ADR-1029): container images and
    # charts (upstream published `ghcr.io/paimonsoror/telltale`; it will never publish `wrendns`),
    # install and download URLs, raw files, the docs a link opens, badges, and the site.
    ("sub", r"ghcr\.io/(?:nbacheller|paimonsoror)/(charts/)?telltale(?:dns)?\b", r"ghcr.io/nbacheller/\1wrendns"),
    ("sub", r"raw\.githubusercontent\.com/paimonsoror/telltaledns", "raw.githubusercontent.com/nbacheller/telltaledns"),
    ("sub", r"github\.com/paimonsoror/telltaledns/(releases|blob|tree|actions|security|commit/)", r"github.com/nbacheller/telltaledns/\1"),
    # the repository a thing points its users or its metadata at (T33.2: only attribution text keeps upstream's):
    # the fetch user agent `(+https://...)`, a quoted URL (`repository = "..."`, an OCI label), a URL ending its
    # line (a chart's `home` and `sources`, a `git clone`), and the release check's default repository
    ("sub", r"(?<=\(\+)https://github\.com/paimonsoror/telltaledns(?=\))", "https://github.com/nbacheller/telltaledns"),
    ("sub", r'(?<=")https://github\.com/paimonsoror/telltaledns(?=")', "https://github.com/nbacheller/telltaledns"),
    ("sub", r"(?<=[ :])https://github\.com/paimonsoror/telltaledns(?=\s*$)", "https://github.com/nbacheller/telltaledns"),
    ("sub", r"(?<=:-)paimonsoror/telltaledns(?=\})", "nbacheller/telltaledns"),
    ("sub", r"img\.shields\.io/github/v/release/paimonsoror/telltaledns", "img.shields.io/github/v/release/nbacheller/telltaledns"),
    # the signing identity of the images (cosign --certificate-identity-regexp), written as a regex
    ("sub", r"github\\\.com/paimonsoror/telltaledns/\\\.github", r"github\\.com/nbacheller/telltaledns/\\.github"),
    ("sub", r"https?://paimonsoror\.github\.io/telltaledns/?", "https://wrendns.com/"),
    ("protect", KEEP_TOKENS),
    # the product's old domains (problem type URIs, the Kubernetes label prefix) move to the new one
    ("sub", r"telltaledns\.(?:dev|io)", "wrendns.com"),
    # the product name in prose
    ("sub", r"TelltaleDNS", "WrenDNS"),
    # the bare word in prose ("Telltale's own RSS"); not the header X-Telltale-Reason
    ("sub", r"\bTelltale\b(?!-)", "WrenDNS"),
    # identifiers: TelltaleError, X-Telltale-Reason
    ("sub", r"Telltale", "Wrendns"),
    # environment variables: TELLTALE_*
    ("sub", r"TELLTALE", "WRENDNS"),
    # the lower-case repository and image spelling, the MCP server name
    ("sub", r"telltaledns", "wrendns"),
    # crates, the binary, paths, metrics, units, labels
    ("sub", r"telltale", "wrendns"),
    # a name cut short in a test's regular expression (`/tellta.*…/`, checking a shortened pod name)
    ("sub", r"tellta(?=\.\*)", "wrend"),
]

KEEP_PATHS = [
    "LICENSE*",
    "brand/*",
    ".github/issues-archive/*",
    "spec/upstream.md",
    "deploy/release/notes/v0.[1-7].[0-9].md",  # the notes of releases already published
    "scripts/rebrand.py",
    ".github/scripts/upstream_watch.py",  # watches upstream by design
    "deploy/docker-desktop/secrets/*",
    # the compatibility shims (ADR-1028): their purpose is to name the old spelling
    "crates/*/src/legacy*.rs",
    "crates/*/src/legacy/*",
    "crates/*/tests/legacy*.rs",
    "integrations/home-assistant/custom_components/*/legacy.py",
    "integrations/home-assistant/CHANGELOG.md",
    "integrations/home-assistant/tests/test_rename.py",
    "deploy/cluster3/compose-prerename.yaml",
    "deploy/systemd/migrate-from-telltale.sh",
    "deploy/systemd/tests/*",
    "deploy/release/legacy-assets.sh",
    "deploy/release/tests/*",
]

# (path glob, first line regex, regex of the line that ends the kept section, exclusive)
KEEP_SECTIONS = [
    ("spec/11-decisions.md", r"^## ADR-1026 ", r"^## ADR-"),
    ("spec/11-decisions.md", r"^## ADR-10(?:2[89]|30) ", r"^## ADR-(?!10(?:2[89]|30) )"),
    # the licence decision names upstream's product as it was called when upstream published it
    ("spec/11-decisions.md", r"^## ADR-1033 ", r"^## ADR-"),
    ("spec/10-roadmap-and-tasks.md", r"^- \[[ x]\] \*\*T33\.", r"^(?!- \[[ x]\] \*\*T33\.)"),
    ("**/CHANGELOG*.md", r"^## \[?v?\d+\.\d+", r"^## (?!\[?v?\d+\.\d+)"),
]

KEEP_LINE_REGEX = [
    (r"*", r'"telltale_version"'),  # the backup manifest field
    (r"*", r'"format":\s*"telltale-backup"'),
    (r"*", r'^\s*"/etc/telltale/secrets",?\s*$'),  # the old secret_file_dirs entry (ADR-1028): one list item on its own line, in the schema
    (r"*", r"migrate-from-telltale\.sh"),  # the migration script's name (its path is in KEEP_PATHS), wherever it is mentioned
]

SKIP_SUFFIXES = {
    ".png", ".jpg", ".jpeg", ".gif", ".ico", ".webp", ".woff", ".woff2", ".ttf", ".otf", ".zst",
    ".gz", ".xz", ".zip", ".tar", ".db", ".bin", ".pdf", ".mmdb", ".wasm",
}

KEEP_INLINE = "rebrand:keep"
KEEP_START = "rebrand:keep-start"
KEEP_END = "rebrand:keep-end"


def path_kept(rel: str) -> bool:
    return any(fnmatch.fnmatchcase(rel, g) for g in KEEP_PATHS)


def glob_match(rel: str, glob: str) -> bool:
    if glob == "*":
        return True
    if glob.startswith("**/"):
        return fnmatch.fnmatchcase(rel, glob[3:]) or fnmatch.fnmatchcase(rel, glob)
    return fnmatch.fnmatchcase(rel, glob)


def apply_rules(text: str) -> str:
    for op, a, *b in RULES:
        if op == "protect":
            for i, tok in enumerate(a):
                sentinel = f"{i}"
                if tok in text:
                    text = text.replace(tok, sentinel)
        else:
            text = re.sub(a, b[0], text)
    for i, tok in enumerate(KEEP_TOKENS):
        text = text.replace(f"{i}", tok)
    return text


def rename_path(rel: str) -> str:
    if path_kept(rel):
        return rel
    return apply_rules(rel)


def transform(rel: str, text: str) -> str:
    sections = [(re.compile(st), re.compile(en)) for g, st, en in KEEP_SECTIONS if glob_match(rel, g)]
    line_keep = [re.compile(r) for g, r in KEEP_LINE_REGEX if glob_match(rel, g)]
    out: list[str] = []
    in_block = False
    in_section: re.Pattern[str] | None = None
    for line in text.splitlines(keepends=True):
        if in_block:
            out.append(line)
            if KEEP_END in line:
                in_block = False
            continue
        if KEEP_START in line:
            in_block = True
            out.append(line)
            continue
        if in_section is not None:
            if in_section.search(line):
                in_section = None
            else:
                out.append(line)
                continue
        if in_section is None:
            for start, end in sections:
                if start.search(line):
                    in_section = end
                    break
            if in_section is not None:
                out.append(line)
                continue
        if KEEP_INLINE in line or any(r.search(line) for r in line_keep):
            out.append(line)
            continue
        out.append(apply_rules(line))
    return "".join(out)


def semver_key(v: str) -> tuple:
    core, _, pre = v.partition("+")[0].partition("-")
    nums = tuple(int(x) if x.isdigit() else 0 for x in core.split("."))
    # a version with a pre-release tag sorts before the release
    return (nums, pre == "", pre)


def sort_cargo_lock(text: str) -> str:
    """Cargo orders `[[package]]` by name then version, and each `dependencies` list likewise."""
    head, *blocks = re.split(r"(?m)^\[\[package\]\]\n", text)
    pkgs = []
    for b in blocks:
        b = b.rstrip("\n") + "\n"
        name = re.search(r'(?m)^name = "([^"]+)"', b).group(1)
        version = re.search(r'(?m)^version = "([^"]+)"', b).group(1)
        source = re.search(r'(?m)^source = "([^"]+)"', b)

        def sort_deps(mm: re.Match[str]) -> str:
            items = re.findall(r'^ "([^"]+)",$', mm.group(2), flags=re.M)
            items.sort(key=lambda s: (s.split(" ")[0], s))
            return mm.group(1) + "".join(f' "{i}",\n' for i in items) + mm.group(3)

        b = re.sub(r"(?ms)(^dependencies = \[\n)(.*?)(^\]\n)", sort_deps, b)
        pkgs.append((name, version, source.group(1) if source else "", b))
    pkgs.sort(key=lambda p: (p[0], semver_key(p[1]), p[2]))
    return head + "\n".join("[[package]]\n" + p[3] for p in pkgs)


def list_files() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT, check=True, capture_output=True,
    ).stdout.decode()
    return sorted({p for p in out.split("\0") if p and (ROOT / p).is_file()})


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if work is left")
    ap.add_argument("--list", action="store_true", help="print each file that would change")
    args = ap.parse_args()

    edits: list[tuple[str, str, bytes | None]] = []  # (old rel, new rel, new bytes or None)
    for rel in list_files():
        new_rel = rename_path(rel)
        data = (ROOT / rel).read_bytes()
        new_data: bytes | None = None
        suffix = Path(rel).suffix.lower()
        if not path_kept(rel) and suffix not in SKIP_SUFFIXES and b"\0" not in data[:8192]:
            try:
                text = data.decode("utf-8")
            except UnicodeDecodeError:
                text = None
            if text is not None:
                new_text = transform(rel, text)
                if Path(rel).name == "Cargo.lock":
                    new_text = sort_cargo_lock(new_text)
                if new_text != text:
                    new_data = new_text.encode("utf-8")
        if new_data is not None or new_rel != rel:
            edits.append((rel, new_rel, new_data))

    if args.check or args.list:
        for rel, new_rel, new_data in edits:
            print(rel if rel == new_rel else f"{rel} -> {new_rel}")
    if args.check:
        if edits:
            print(f"rebrand: {len(edits)} file(s) still to rename (run scripts/rebrand.py)", file=sys.stderr)
            return 1
        print("rebrand: nothing left to rename")
        return 0
    if args.list:
        return 0

    for rel, new_rel, new_data in edits:
        src, dst = ROOT / rel, ROOT / new_rel
        if new_data is not None:
            src.write_bytes(new_data)
        if new_rel != rel:
            dst.parent.mkdir(parents=True, exist_ok=True)
            if dst.exists():
                print(f"rebrand: {new_rel} already exists, leaving {rel}", file=sys.stderr)
                return 2
            src.replace(dst)
    # drop directories the moves emptied
    for d in sorted({(ROOT / r).parent for r, n, _ in edits if r != n}, key=lambda p: -len(p.parts)):
        p = d
        while p != ROOT and p.is_dir() and not any(p.iterdir()):
            p.rmdir()
            p = p.parent
    print(f"rebrand: {len(edits)} file(s) changed or renamed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
