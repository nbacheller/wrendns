#!/usr/bin/env python3
# SPDX-License-Identifier: AGPL-3.0-or-later
"""Every source file added since the licence change carries an AGPL SPDX header (ADR-1033, ADR-1035).

WrenDNS is AGPL-3.0-or-later from the commit after the annotated tag `permissive-final`, the last
version released entirely under Apache-2.0 OR MIT. A source file added after that tag must say so
in its first lines:

    // SPDX-License-Identifier: AGPL-3.0-or-later          (.rs, .ts, .js)
    # SPDX-License-Identifier: AGPL-3.0-or-later           (.py, .sh; after a shebang)
    <!-- SPDX-License-Identifier: AGPL-3.0-or-later -->    (.svelte)

Files that existed at the tag are not touched (no mass edit): they keep the project's licence
through LICENSE and NOTICE, and upstream's portions keep their MIT/Apache-2.0 notices.

Out of scope: generated files (a comment line at the top that starts with "@generated",
"GENERATED by" or "auto-generated", or says "generated by ...; do not edit"), vendored code (`node_modules/`, `vendor/`, `third_party/`), test data
(`testdata/`, `fixtures/`), the issue archive, and `integrations/home-assistant/`, which is
Apache-2.0 and ships on its own.

"Added" is `git diff --diff-filter=A` from the tag to the working tree (a move, 90% or more like a deleted
file, is not an addition),
plus untracked files that git does not ignore, so a local run catches a file before it is committed.

Usage: python3 scripts/check-spdx.py [--base permissive-final]   (exit 1 lists the files to fix)
CI runs it with the full history (`fetch-depth: 0`), because it needs the tag.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

HEADER = "SPDX-License-Identifier: AGPL-3.0-or-later"
EXTENSIONS = {".rs", ".ts", ".svelte", ".py", ".sh", ".js"}
# Directory prefixes and path parts that are never checked.
EXCLUDED_PREFIXES = (
    "integrations/home-assistant/",
    ".github/issues-archive/",
    "site/_site/",
    "ui/dist/",
)
EXCLUDED_PARTS = {"node_modules", "vendor", "third_party", "testdata", "fixtures"}
# How far down the header may sit (a shebang, an encoding line or a doc comment opener may come first).
HEAD_LINES = 5
# A generator's marker counts only as a comment of its own (a line that starts with a comment
# opener), so an ordinary comment that mentions generated output doesn't exempt the file.
COMMENT_OPENER = r"^\s*(?://+!?|#|/\*+|\*|<!--|--)\s*"
GENERATED = re.compile(
    COMMENT_OPENER
    + r"(?:@generated\b|generated by\b|(?:this file (?:was|is) )?auto-generated\b"
    + r"|.*\bgenerated by\b.*\bdo not edit\b|.*\bdo not make direct changes\b)",
    re.IGNORECASE,
)
# A file counts as renamed (and so not new) only when it is at least this similar to a deleted
# one; git's default of 50% would let a new file that borrows half of an old one through.
RENAME_SIMILARITY = "-M90%"


def in_scope(path: str) -> bool:
    if Path(path).suffix not in EXTENSIONS:
        return False
    if path.startswith(EXCLUDED_PREFIXES):
        return False
    return not (set(Path(path).parts[:-1]) & EXCLUDED_PARTS)


def head(text: str, n: int) -> list[str]:
    return text.splitlines()[:n]


def is_generated(text: str) -> bool:
    return any(GENERATED.search(line) for line in head(text, 3))


def has_header(text: str) -> bool:
    return any(HEADER in line for line in head(text, HEAD_LINES))


def git(*args: str) -> list[str]:
    out = subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout
    return [line for line in out.splitlines() if line]


def added_files(base: str) -> list[str]:
    try:
        git("rev-parse", "--verify", "--quiet", f"{base}^{{commit}}")
    except subprocess.CalledProcessError:
        sys.exit(
            f"check-spdx: {base!r} is not in this clone; fetch the tags and full history "
            "(git fetch --tags --unshallow, or actions/checkout with fetch-depth: 0)"
        )
    added = git("diff", "--name-only", RENAME_SIMILARITY, "--diff-filter=A", base, "--")
    untracked = git("ls-files", "--others", "--exclude-standard")
    return sorted(set(added) | set(untracked))


def missing(paths: list[str], root: Path) -> list[str]:
    bad = []
    for path in paths:
        if not in_scope(path):
            continue
        file = root / path
        if not file.is_file():
            continue
        text = file.read_text(encoding="utf-8", errors="replace")
        if is_generated(text) or has_header(text):
            continue
        bad.append(path)
    return bad


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base", default="permissive-final", help="the tag or commit of the licence change")
    args = ap.parse_args()
    root = Path(git("rev-parse", "--show-toplevel")[0])
    paths = added_files(args.base)
    bad = missing(paths, root)
    checked = sum(1 for p in paths if in_scope(p))
    if bad:
        print(f"check-spdx: {len(bad)} file(s) added since {args.base} lack '{HEADER}' in their first {HEAD_LINES} lines:")
        for path in bad:
            print(f"  {path}")
        return 1
    print(f"check-spdx: ok ({checked} source file(s) added since {args.base}, all with the AGPL header or generated)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
